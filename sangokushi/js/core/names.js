// ------------------------------------------------------------------
function pair(rng, table) { return rng.pick(table); }

/** 중복 방지용 이름 저장소 */
export class NameRegistry {
  constructor() { this.used = new Set(); }
  claim(key) { if (this.used.has(key)) return false; this.used.add(key); return true; }
}

/** 인물 이름 생성 → { name, hanja, surname, given, courtesy, courtesyHanja } */
export function makePersonName(rng, registry = null) {
  for (let attempt = 0; attempt < 60; attempt++) {
    const sn = pair(rng, SURNAMES);
    const len = rng.percent(72) ? 1 : 2;           // 외자 이름이 다수
    let gKo = '', gHa = '';
    for (let i = 0; i < len; i++) {
      const c = pair(rng, NAME_CHARS);
      gKo += c[0]; gHa += c[1];
    }
    const full = sn[0] + gKo;
    if (registry && !registry.claim(full)) continue;
    const ch = pair(rng, COURTESY_HEAD);
    const ct = pair(rng, NAME_CHARS);
    return {
      name: full,
      hanja: sn[1] + gHa,
      surname: sn[0], surnameHanja: sn[1],
      given: gKo, givenHanja: gHa,
      courtesy: ch[0] + ct[0],
      courtesyHanja: ch[1] + ct[1],
    };
  }
  // 최후 수단 — 숫자를 붙여 유일성 확보
  const sn = pair(rng, SURNAMES), c = pair(rng, NAME_CHARS);
  const n = sn[0] + c[0] + rng.int(999);
  return {
    name: n, hanja: sn[1] + c[1], surname: sn[0], surnameHanja: sn[1],
    given: c[0], givenHanja: c[1], courtesy: '무명', courtesyHanja: '無名',
  };
}

/** 도시 이름 */
export function makeCityName(rng, registry = null) {
  for (let attempt = 0; attempt < 80; attempt++) {
    const a = pair(rng, PLACE_HEAD), b = pair(rng, PLACE_TAIL);
    const full = a[0] + b[0];
    if (a[1] === b[1]) continue;
    if (registry && !registry.claim('city:' + full)) continue;
    return { name: full, hanja: a[1] + b[1] };
  }
  const a = pair(rng, PLACE_HEAD);
  return { name: a[0] + '성' + rng.int(99), hanja: a[1] + '城' };
}

/** 주(州) 이름 */
export function makeProvinceName(rng, registry = null) {
  for (let attempt = 0; attempt < 60; attempt++) {
    const a = pair(rng, PROVINCE_HEAD);
    const full = a[0] + '주';
    if (registry && !registry.claim('prov:' + full)) continue;
    return { name: full, hanja: a[1] + '州' };
  }
  const a = pair(rng, PROVINCE_HEAD);
  return { name: a[0] + '주' + rng.int(9), hanja: a[1] + '州' };
}

